    DECLARE @AdminRoleId NVARCHAR(450) = (SELECT Id FROM AspNetRoles WHERE Name = 'Admin')
    DECLARE @CtshipAdminRoleId NVARCHAR(450) = (SELECT Id FROM AspNetRoles WHERE Name = 'CTSHIPAdmin')
    
    -- Password hash for "Admin@2025" generated by ASP.NET Identity
    DECLARE @PasswordHash NVARCHAR(MAX) = 'AQAAAAIAAYagAAAAELmX3l3q2K2W0W0W0W0W0W0W0W0W0W0W0W0W0W0W0W0W0W0W0W0W0W0W0W0W0W0W0W0W0W0W0W0W0W0W0='
    
    INSERT INTO AspNetUsers (
        Id, UserName, NormalizedUserName, Email, NormalizedEmail, 
        EmailConfirmed, PasswordHash, SecurityStamp, ConcurrencyStamp, 
        PhoneNumber, PhoneNumberConfirmed, TwoFactorEnabled, LockoutEnabled, 
        LockoutEnd, AccessFailedCount, FullName, State
