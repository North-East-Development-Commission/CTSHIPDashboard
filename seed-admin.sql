-- Quick admin user seeding for SQL Server
-- Run this in SQL Server Management Studio or Azure Data Studio against CTSHIPDashboard database

-- Create admin role
IF NOT EXISTS (SELECT 1 FROM AspNetRoles WHERE Name = 'Admin')
    INSERT INTO AspNetRoles (Id, Name, NormalizedName, ConcurrencyStamp)
    VALUES (NEWID(), 'Admin', 'ADMIN', NEWID());

IF NOT EXISTS (SELECT 1 FROM AspNetRoles WHERE Name = 'CTSHIPAdmin')
    INSERT INTO AspNetRoles (Id, Name, NormalizedName, ConcurrencyStamp)
    VALUES (NEWID(), 'CTSHIPAdmin', 'CTSCHIPADMIN', NEWID());

-- Create admin user if not exists
IF NOT EXISTS (SELECT 1 FROM AspNetUsers WHERE Email = 'as.maiwada@nedc.gov.ng')
BEGIN
